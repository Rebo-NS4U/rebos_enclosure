const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const base = require('node:path').resolve(__dirname, '../../system/apps/shell') + '/';
const service = fs.readFileSync(base + 'modules/services/NetworkService.qml', 'utf8');
const body = service.split('    function updateFriendlyList() {')[1].split('\n    Component {')[0];
const a = {ssid:'a', strength:10, askingPassword:true};
const b = {ssid:'b', strength:90};
const ctx = {wifiNetworks:[a,b], friendlyWifiNetworks:[a,b], wifiConnectTarget:null, updateActive(){}};
vm.createContext(ctx);
const original = ctx.friendlyWifiNetworks;
vm.runInContext('function updateFriendlyList() {' + body, ctx);
ctx.updateFriendlyList();
assert.equal(ctx.friendlyWifiNetworks, original, 'prompt survives signal reorder');
ctx.wifiNetworks.push({ssid:'c', strength:100});
ctx.updateFriendlyList();
assert.equal(ctx.friendlyWifiNetworks, original, 'prompt survives new network');
a.askingPassword=false; ctx.wifiConnectTarget=a;
ctx.updateFriendlyList();
assert.equal(ctx.friendlyWifiNetworks, original, 'submission survives refresh');
ctx.wifiConnectTarget=null; ctx.updateFriendlyList();
assert.equal(ctx.friendlyWifiNetworks[0].ssid,'c', 'sorting resumes after submission');
assert(service.includes('!found && !rn.askingPassword && rn !== root.wifiConnectTarget'));
const item=fs.readFileSync(base+'modules/widgets/dashboard/controls/WifiNetworkItem.qml','utf8');
const submit=item.split('    function submitPassword() {')[1].split('\n    implicitHeight:')[0];
let calls=[];
const ui={passwordInput:{text:'test password'},NetworkService:{isUpdating:false,changePassword(n,p){calls.push(p)}},root:{network:a}};
vm.createContext(ui); vm.runInContext('function submitPassword() {'+submit,ui);
ui.submitPassword(); assert.deepEqual(calls,['test password']); assert.equal(ui.passwordInput.text,'');
ui.submitPassword(); assert.equal(calls.length,1);
ui.passwordInput.text='draft'; ui.NetworkService.isUpdating=true; ui.submitPassword(); assert.equal(ui.passwordInput.text,'draft');
console.log('Wi-Fi prompt regression checks passed');
