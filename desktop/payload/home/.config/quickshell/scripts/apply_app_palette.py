def apply(p, home, refresh=True):
    bg, fg, accent = p['background'], p['overSurface'], p['primary']
    surface, muted, border = p['surfaceContainer'], p['outline'], p['outlineVariant']
    dark = sum(int(bg[i:i+2], 16) * weight for i, weight in ((1, .299), (3, .587), (5, .114))) < 128
    cache = home / '.cache/rebos_shell'
    write(cache / 'effective-palette.json', json.dumps(p, indent=2) + '\n')
    apply_zen_palette(p, home)
    apply_spotify_palette(p, home, refresh)

    colors = {'foreground': fg, 'focusBorder': accent,
              'selection.background': accent + '55', 'descriptionForeground': muted,
              'errorForeground': p['red'], 'widget.border': border}
    for area in ('editor', 'sideBar', 'activityBar', 'statusBar', 'titleBar.active',
                 'titleBar.inactive', 'panel', 'editorGroupHeader.tabs', 'breadcrumb',
                 'input', 'dropdown', 'editorWidget', 'quickInput', 'notificationCenter',
                 'notifications', 'menu'):
        colors[area + '.background'] = surface if area in ('input', 'dropdown', 'editorWidget', 'quickInput', 'menu') else bg
    for area in ('editor', 'sideBar', 'activityBar', 'statusBar', 'titleBar.active',
                 'titleBar.inactive', 'panelTitle.active', 'input', 'dropdown',
                 'breadcrumb', 'notifications', 'menu', 'quickInput'):
        colors[area + '.foreground'] = fg
    # These roles use camelCase rather than dotted suffixes in VS Code.
    for old, new in [('titleBar.active.background', 'titleBar.activeBackground'),
                     ('titleBar.inactive.background', 'titleBar.inactiveBackground'),
                     ('titleBar.active.foreground', 'titleBar.activeForeground'),
                     ('titleBar.inactive.foreground', 'titleBar.inactiveForeground'),
                     ('editorGroupHeader.tabs.background', 'editorGroupHeader.tabsBackground'),
                     ('panelTitle.active.foreground', 'panelTitle.activeForeground')]:
        colors[new] = colors.pop(old)
    colors.update({'editorCursor.foreground': accent, 'editorLineNumber.foreground': muted,
                   'editorLineNumber.activeForeground': fg, 'editor.selectionBackground': accent + '55',
                   'editor.lineHighlightBackground': surface,
                   'tab.activeBackground': surface, 'tab.activeForeground': fg,
                   'tab.inactiveBackground': bg, 'tab.inactiveForeground': muted,
                   'tab.activeBorderTop': accent, 'activityBar.activeBorder': accent,
                   'list.activeSelectionBackground': accent,
                   'list.activeSelectionForeground': p['overPrimary'],
                   'list.inactiveSelectionBackground': surface,
                   'list.hoverBackground': surface, 'button.background': accent,
                   'button.foreground': p['overPrimary'], 'button.hoverBackground': p['secondary'],
                   'progressBar.background': accent, 'badge.background': accent,
                   'badge.foreground': p['overPrimary'], 'terminal.background': bg,
                   'terminal.foreground': fg, 'terminalCursor.foreground': accent})
    for name, role in [('Black', 'surfaceContainerLowest'), ('Red', 'red'), ('Green', 'green'),
                       ('Yellow', 'yellow'), ('Blue', 'blue'), ('Magenta', 'magenta'),
                       ('Cyan', 'cyan'), ('White', 'overSurface')]:
        colors['terminal.ansi' + name] = p[role]
        colors['terminal.ansiBright' + name] = p.get('light' + name, p[role])
    settings = home / '.config/Code/User/settings.json'
    text = settings.read_text() if settings.exists() else '{}\n'
    old = read_jsonc(text)
    custom = old.get('workbench.colorCustomizations', {}).copy()
    for key in ('titleBar.active.background', 'titleBar.inactive.background',
                'titleBar.active.foreground', 'titleBar.inactive.foreground',
                'editorGroupHeader.tabs.background', 'panelTitle.active.foreground'):
        custom.pop(key, None)
    custom.update(colors)
    tokens = old.get('editor.tokenColorCustomizations', {}).copy()
    rules = [rule for rule in tokens.get('textMateRules', [])
             if not rule.get('name', '').startswith('rebos_shell:')]
    for scope, role in [('comment', 'outline'), ('string', 'green'), ('keyword', 'primary'),
                        ('constant.numeric', 'tertiary'), ('entity.name.function', 'blue'),
                        ('entity.name.type', 'secondary'), ('variable', 'overSurface')]:
        rules.append({'name': 'rebos_shell:' + scope, 'scope': scope,
                      'settings': {'foreground': p[role]}})
    tokens['textMateRules'] = rules
    semantic = old.get('editor.semanticTokenColorCustomizations', {}).copy()
    semantic_rules = semantic.get('rules', {}).copy()
    for token, role in [('type', 'secondary'), ('class', 'secondary'), ('enum', 'secondary'),
                        ('interface', 'secondary'), ('namespace', 'secondary'),
                        ('function', 'blue'), ('method', 'blue'), ('variable', 'overSurface'),
                        ('parameter', 'overSurface'), ('property', 'overSurface'),
                        ('string', 'green'), ('keyword', 'primary'),
                        ('number', 'tertiary'), ('comment', 'outline')]:
        semantic_rules[token] = p[role]
    semantic['rules'] = semantic_rules
    write(settings, patch_jsonc(text, {'workbench.colorTheme': 'Dark Modern' if dark else 'Light Modern',
                                     'workbench.colorCustomizations': custom,
                                     'editor.tokenColorCustomizations': tokens,
                                     'editor.semanticTokenColorCustomizations': semantic}))


if __name__ == '__main__':
    try:
        home = Path.home()
        palette = json.loads((home / '.cache/rebos_shell/effective-palette.json').read_text())
        apply(palette, home)
    except (OSError, ValueError, KeyError) as error:
        print(json.dumps({'error': str(error)}), file=sys.stderr)
        sys.exit(1)
