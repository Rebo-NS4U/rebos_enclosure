TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*[\s\S]*?\*/|\s+|[{}\[\],:]|[^\s{}\[\],:]+')


def jsonc_tokens(text):
    return [m for m in TOKEN.finditer(text)
            if not m.group().isspace() and not m.group().startswith(('//', '/*'))]


def read_jsonc(text):
    tokens = jsonc_tokens(text)
    clean = ''.join(m.group() for i, m in enumerate(tokens)
                    if not (m.group() == ',' and i + 1 < len(tokens)
                            and tokens[i + 1].group() in ('}', ']')))
    return json.loads(clean)


def patch_jsonc(text, values):
    """Edit top-level settings while retaining unrelated text and comments."""
    if not text.strip():
        text = '{}\n'
    data = read_jsonc(text)
    if not isinstance(data, dict):
        raise ValueError('VS Code settings must be an object')
    tokens = jsonc_tokens(text)
    spans = {}
    depth = 0
    for i, token in enumerate(tokens):
        value = token.group()
        if depth == 1 and value.startswith('"') and tokens[i + 1].group() == ':':
            name = json.loads(value)
            start = tokens[i + 2].start()
            nesting = 0
            for end_token in tokens[i + 2:]:
                part = end_token.group()
                if nesting == 0 and part in (',', '}'):
                    spans[name] = (start, end_token.start())
                    break
                if part in ('{', '['):
                    nesting += 1
                elif part in ('}', ']'):
                    nesting -= 1
        if value in ('{', '['):
            depth += 1
        elif value in ('}', ']'):
            depth -= 1
    edits = []
    missing = {}
    for key, value in values.items():
        if key in data and data[key] == value:
            continue
        if key in spans:
            edits.append((*spans[key], json.dumps(value, indent=4)))
        else:
            missing[key] = value
    for start, end, value in sorted(edits, reverse=True):
        text = text[:start] + value + text[end:]
    if missing:
        tokens = jsonc_tokens(text)
        close = tokens[-1].start()
        separator = ',' if len(tokens) > 2 and tokens[-2].group() != ',' else ''
        fragment = ',\n'.join('    ' + json.dumps(k) + ': ' + json.dumps(v, indent=4)
                               for k, v in missing.items())
        # Insert before closing brace; keep any trailing comments in place.
        text = text[:close] + separator + '\n' + fragment + '\n' + text[close:]
    read_jsonc(text)
    return text


def zen_profiles(home):
    roots = [home / '.zen', home / '.config/zen',
             home / '.var/app/app.zen_browser.zen/.zen',
             home / '.var/app/app.zen_browser.zen/zen']
    for root in roots:
        ini = root / 'profiles.ini'
        if not ini.exists():
            continue
        config = configparser.ConfigParser(interpolation=None)
        config.read(ini)
        for section in config.sections():
            if not section.startswith('Profile') or not config.has_option(section, 'Path'):
                continue
            path = Path(config.get(section, 'Path'))
            if config.get(section, 'IsRelative', fallback='1') == '1':
                path = root / path
            if path.is_dir():
                yield path


