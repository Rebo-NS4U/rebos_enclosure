def apply_spotify_palette(p, home, refresh=True):
    bg, fg, accent = p['background'], p['overSurface'], p['primary']
    surface, muted, border = p['surfaceContainer'], p['outline'], p['outlineVariant']
    theme = home / '.config/spicetify/Themes/rebos_shell'
    spotify = {'text': fg, 'subtext': muted, 'main': bg, 'sidebar': bg, 'player': bg,
               'card': surface, 'shadow': p['surfaceContainerLowest'],
               'selected-row': p['primaryContainer'], 'button': accent,
               'button-active': p['secondary'], 'button-disabled': border,
               'tab-active': p['secondaryContainer'], 'notification': p['tertiaryContainer'],
               'notification-error': p['red'], 'misc': accent}
    changed = write(theme / 'color.ini', '[rebos_shell]\n' + ''.join(
        f'{key} = {value[1:]}\n' for key, value in spotify.items()))
    changed = write(theme / 'user.css', spotify_css(p)) or changed
    spice_config = home / '.config/spicetify/config-xpui.ini'
    if spice_config.exists():
        update_ini(spice_config, {'Setting': {'current_theme': 'rebos_shell',
                   'color_scheme': 'rebos_shell', 'inject_css': '1', 'replace_colors': '1'}})
        executable = shutil.which('spicetify')
        local = home / '.spicetify/spicetify'
        if not executable and local.is_file():
            executable = str(local)
        config = configparser.ConfigParser(interpolation=None)
        config.read(spice_config)
        # Never run backup/apply or restart Spotify on ordinary palette changes.
        destination = Path(config.get('Setting', 'spotify_path', fallback='/nonexistent'))
        if refresh and changed and executable and (destination / 'Apps/xpui').is_dir():
            try:
                result = subprocess.run([executable, 'refresh', '--no-restart'], capture_output=True, text=True, timeout=30)
                if result.returncode:
                    print(json.dumps({'error': 'Spicetify color refresh failed'}), file=sys.stderr)
            except subprocess.TimeoutExpired:
                print(json.dumps({'error': 'Spicetify color refresh timed out'}), file=sys.stderr)



