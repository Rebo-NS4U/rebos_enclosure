#!/usr/bin/env python3
"""Read-only hardware discovery and machine policy, independent of deployment."""
from pathlib import Path
import json
import re
import shutil
import subprocess

MODE = re.compile(r'([1-9][0-9]{1,4})x([1-9][0-9]{1,4})(?:@([1-9][0-9]{0,3}(?:\.[0-9]{1,3})?))?')
PACKAGE = re.compile(r'[a-zA-Z0-9@_+][a-zA-Z0-9@_+.-]*')

PROFILES = ('auto', 'desktop', 'laptop', 'virtual')
LAPTOP_CHASSIS = {'8', '9', '10', '11', '14', '30', '31', '32'}


def read(path):
    try:
        return path.read_text().strip()
    except OSError:
        return ''


def capabilities(sysfs=Path('/sys'), virtual=None):
    if virtual is None:
        try:
            result = subprocess.run(['systemd-detect-virt', '--vm'], capture_output=True,
                                    text=True, timeout=3)
            virtual = result.stdout.strip() if result.returncode == 0 else ''
        except (OSError, subprocess.TimeoutExpired):
            virtual = ''
    power = sysfs / 'class/power_supply'
    battery = any(read(p / 'type') == 'Battery' for p in power.glob('*'))
    chassis = read(sysfs / 'class/dmi/id/chassis_type')
    return {'battery': battery, 'portable': battery or chassis in LAPTOP_CHASSIS,
            'bluetooth': any((sysfs / 'class/bluetooth').glob('hci*')),
            'backlight': any((sysfs / 'class/backlight').glob('*')),
            'virtualization': virtual or ''}


def machine_policy(profile, detected):
    if profile not in PROFILES:
        raise ValueError('Unknown machine profile: ' + str(profile))
    if not isinstance(detected, dict):
        raise ValueError('Hardware capabilities must be an object')
    selected = profile
    if selected == 'auto':
        selected = ('virtual' if detected.get('virtualization') else
                    'laptop' if detected.get('portable') else 'desktop')
    return {'requested': profile, 'profile': selected,
            'capabilities': dict(detected),
            'numlock': selected == 'desktop', 'animations': selected != 'virtual'}


def render(machine):
    # Keep the policy deliberately small: no vendor fan control, connector names,
    # forced renderer, CPU governor, suspend policy or driver module mutations.
    if not isinstance(machine, dict):
        raise ValueError('Machine settings must be an object')
    profile = machine.get('profile')
    expected = machine_policy(profile, machine.get('capabilities', {}))
    if profile == 'auto' or any(machine.get(k) is not expected[k] for k in ('numlock', 'animations')):
        raise ValueError('Invalid resolved machine policy')
    lines = ['// Local machine policy generated by Enclosure setup.']
    if machine['numlock']:
        lines += ['input { keyboard { numlock; }; }']
    if not machine['animations']:
        lines += ['animations { off; }']
    return '\n'.join(lines) + '\n'


def run(args):
    try:
        result = subprocess.run(args, text=True, capture_output=True, timeout=3)
        return result.stdout if result.returncode == 0 else ''
    except (OSError, subprocess.TimeoutExpired):
        return ''


# Quality exception: The detector names independent CPU, GPU, kernel and display probes; partial hardware availability is expected.
# Numeric ceilings are enforced by desktop/scripts/quality.py.
def detect(sysfs=Path('/sys'), cpuinfo_path=Path('/proc/cpuinfo'),  # pylint: disable=too-many-branches,too-many-locals
           modules_path=Path('/usr/lib/modules'), command=run, virtual=None):
    cpuinfo = read(cpuinfo_path)
    cpu = 'intel' if 'GenuineIntel' in cpuinfo else 'amd' if 'AuthenticAMD' in cpuinfo else 'unknown'
    vendors = set()
    for device in (sysfs / 'bus/pci/devices').glob('*'):
        try:
            if (device / 'class').read_text().strip().startswith('0x03'):
                vendor = {'0x8086': 'intel', '0x1002': 'amd', '0x10de': 'nvidia'}.get((device / 'vendor').read_text().strip())
                if vendor:
                    vendors.add(vendor)
        except OSError:
            pass
    descriptions = [line for line in command(['lspci', '-nn']).splitlines()
                    if any(kind in line.lower() for kind in ('vga compatible', '3d controller', 'display controller'))]
    installed = command(['pacman', '-Qq']).splitlines()
    kernels = sorted(set(installed) & {'linux', 'linux-lts', 'linux-zen', 'linux-hardened'})
    for pkgbase in modules_path.glob('*/pkgbase'):
        try:
            kernel = pkgbase.read_text().strip()
            if PACKAGE.fullmatch(kernel) and kernel not in kernels:
                kernels.append(kernel)
        except OSError:
            pass
    outputs = []
    try:
        data = json.loads(command(['niri', 'msg', '--json', 'outputs']) or '{}')
        for name, output in data.items():
            modes = [f'{m["width"]}x{m["height"]}@{m["refresh_rate"]/1000:.3f}' for m in output.get('modes', [])]
            outputs.append({'name': name, 'modes': list(dict.fromkeys(modes))})
    except (ValueError, TypeError, KeyError, AttributeError):
        outputs = []
    if not outputs:
        for path in sorted((sysfs / 'class/drm').glob('card*-*')):
            try:
                if (path / 'status').read_text().strip() != 'connected':
                    continue
                name = re.sub(r'^card[0-9]+-', '', path.name)
                modes = [m for m in (path / 'modes').read_text().splitlines() if MODE.fullmatch(m)]
                if name not in {o['name'] for o in outputs}:
                    outputs.append({'name': name, 'modes': list(dict.fromkeys(modes))})
            except OSError:
                pass
    return {'cpu': cpu, 'gpus': sorted(vendors), 'gpu_descriptions': descriptions,
            'kernels': sorted(kernels), 'installed': installed, 'outputs': outputs,
            'mkinitcpio': bool(shutil.which('mkinitcpio')), 'capabilities': capabilities(sysfs, virtual)}
