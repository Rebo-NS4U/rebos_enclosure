// Export portable defaults directly from Dweebo's QML theme sources.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const evaluate = path => { const context = vm.createContext({}); vm.runInContext(read(path).replace(/^\.pragma library\s*/m, ''), context); return context; };
const defaults = evaluate('../config/defaults/theme.js').data;
const styles = evaluate('../modules/theme/ShellStyles.js');
const colors = Object.fromEntries([...read('../modules/theme/Colors.qml').matchAll(/property color (\w+): "(#[0-9a-f]+)"/g)].map(m => [m[1], m[2]]));
const palette = {background: colors.background, foreground: colors.overBackground, primary: colors.primary, onPrimary: colors.overPrimary, secondary: colors.secondary, onSecondary: colors.overSecondary, tertiary: colors.tertiary, onTertiary: colors.overTertiary, error: colors.error, onError: colors.overError};
// Tinted is the requested visual reference. Palette values remain overridable.
let css = '/* Generated by export.mjs from Dweebo. */\n.dweebo {\n';
for (const [key, value] of Object.entries(palette)) css += `  --dw-${key}: ${value};\n`;
css += `  --dw-font: "${defaults.font}", monospace;\n  --dw-font-size: ${defaults.fontSize}px;\n  --dw-radius: ${defaults.roundness}px;\n  --dw-duration: ${defaults.animDuration}ms;\n`;
for (const variant of ['bg', 'pane', 'focus']) {
 const s = styles.surface('colorful', variant, palette, defaults.ditherStrength);
 css += `  --dw-${variant}: ${s.gradient[0][0]};\n`;
}
css += '}\n';
writeFileSync(new URL('tokens.css', import.meta.url), css);
