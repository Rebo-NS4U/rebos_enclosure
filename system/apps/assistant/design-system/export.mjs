// Export portable defaults directly from Dweebo's QML theme sources.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const evaluate = path => { const context = vm.createContext({}); vm.runInContext(read(path).replace(/^\.pragma library\s*/m, ''), context); return context; };
const defaults = evaluate('../config/defaults/theme.js').data;
const styles = evaluate('../modules/theme/ShellStyles.js');
const colors = Object.fromEntries([...read('../modules/theme/Colors.qml').matchAll(/property color (\w+): "(#[0-9a-f]+)"/g)].map(m => [m[1], m[2]]));
const palette = {background: colors.background, foreground: colors.overBackground, primary: colors.primary, onPrimary: colors.overPrimary, secondary: colors.secondary, onSecondary: colors.overSecondary, tertiary: colors.tertiary, onTertiary: colors.overTertiary, error: colors.error, onError: colors.overError};
// Monochrome adapters use the same surface hierarchy with neutral role colors.
const monochrome = light => {
 const foreground = light ? '#161616' : '#eeeeee';
 const background = light ? '#ffffff' : '#000000';
 return {background, foreground, primary: foreground, onPrimary: background,
  secondary: light ? '#444444' : '#cccccc', onSecondary: background,
  tertiary: light ? '#555555' : '#bbbbbb', onTertiary: background,
  error: foreground, onError: background};
};
let css = '/* Generated by export.mjs from Dweebo. */\n.dweebo {\n';
css += `  --dw-font: "${defaults.font}", monospace;\n  --dw-font-size: ${defaults.fontSize}px;\n  --dw-radius: ${defaults.roundness}px;\n  --dw-duration: ${defaults.animDuration}ms;\n}\n`;
for (const mode of ['color', 'black', 'white']) {
 const p = mode === 'color' ? palette : monochrome(mode === 'white');
 // Defaults first; explicit surface variants follow for each palette.
 for (const style of ['colorful', 'glass', 'quiet', 'dithered']) {
  const root = mode === 'color' ? '.dweebo' : `.dweebo[data-theme="${mode}"]`;
  const selector = `${root}[data-style="${style}"]`;
  css += `${style === 'colorful' ? root + ',\n' : ''}${selector} {\n`;
  css += `  color-scheme: ${mode === 'white' ? 'light' : 'dark'};\n`;
  for (const [key, value] of Object.entries(p)) css += `  --dw-${key}: ${value};\n`;
  for (const variant of ['bg', 'pane', 'focus']) {
   const s = styles.surface(style, variant, p, defaults.ditherStrength);
   css += `  --dw-${variant}: color-mix(in srgb, ${s.gradient[0][0]} ${s.opacity * 100}%, transparent);\n`;
   if (variant === 'pane') {
    css += `  --dw-texture: ${s.gradientType === 'halftone' ? `radial-gradient(${s.halftoneDotColor} 0.65px, transparent 0.85px)` : 'none'};\n`;
    css += `  --dw-texture-size: ${s.halftoneDotMax || 1}px;\n`;
   }
  }
  css += '}\n';
 }
}
writeFileSync(new URL('tokens.css', import.meta.url), css);
