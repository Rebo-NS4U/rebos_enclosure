#!/usr/bin/env python3
"""Generate a validated Niri blur override without editing the user's profile."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

MODES = ('medium', 'light', 'shell', 'off')


def render(mode):
    if mode not in MODES:
        raise ValueError('Unknown desktop blur mode')
    passes, offset = (2, 2.0) if mode == 'light' else (3, 3.0)
    text = ('// Generated by Settings > Appearance > Blur.\n'
            f'blur {{ passes {passes}; offset {offset}; noise 0.02; saturation 1.0; }}\n')
    if mode in ('shell', 'off'):
        text += ('window-rule {\n'
                 '    background-effect { blur false; }\n'
                 '    popups { background-effect { blur false; }; }\n'
                 '}\nlayer-rule {\n')
        if mode == 'shell':
            # Retain client-supplied regions; do not turn a shaped panel into
            # a blurred full-screen transparent surface.
            text += '    exclude namespace=r#"^rebos_shell(?::.*)?$"#\n'
        text += ('    background-effect { blur false; }\n'
                 '    popups { background-effect { blur false; }; }\n'
                 '}\n')
    return text


def apply(mode, target):
    content = render(mode)
    target = Path(target).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists() and target.read_text() == content:
        return
    fd, name = tempfile.mkstemp(prefix='.desktop-blur-', suffix='.kdl', dir=target.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        result = subprocess.run(['niri', 'validate', '-c', name], capture_output=True, text=True, timeout=10)
        if result.returncode:
            raise RuntimeError(result.stderr.strip() or 'Niri rejected the blur settings')
        os.replace(name, target)
    finally:
        Path(name).unlink(missing_ok=True)


if __name__ == '__main__':
    try:
        apply(sys.argv[1], sys.argv[2])
        print(json.dumps({'ok': True, 'mode': sys.argv[1]}))
    except (OSError, ValueError, RuntimeError, IndexError, subprocess.TimeoutExpired) as error:
        print(json.dumps({'ok': False, 'error': str(error)}))
        sys.exit(1)
